using Trazza.Platform.Matchmaking.Application.CommandServices;
using Trazza.Platform.Matchmaking.Application.Internal.OutboundServices;
using Trazza.Platform.Matchmaking.Domain.Model.Aggregates;
using Trazza.Platform.Matchmaking.Domain.Model.Commands;
using Trazza.Platform.Matchmaking.Domain.Model.Errors;
using Trazza.Platform.Matchmaking.Domain.Repositories;
using Trazza.Platform.Shared.Application.Model;
using Trazza.Platform.Shared.Domain.Repositories;

namespace Trazza.Platform.Matchmaking.Application.Internal.CommandServices;

public class ReturnRouteCommandService(
    IReturnRouteRepository returnRouteRepository,
    IProfilesService profilesService,
    IUnitOfWork unitOfWork)
    : IReturnRouteCommandService
{
    public async Task<Result<ReturnRoute>> Handle(PublishReturnRouteCommand command,
        CancellationToken cancellationToken)
    {
        if (!command.Origin.IsValid || !command.Destination.IsValid)
            return Result<ReturnRoute>.Failure(MatchmakingErrors.InvalidAddress);
        if (command.DepartureAt <= DateTimeOffset.UtcNow)
            return Result<ReturnRoute>.Failure(MatchmakingErrors.DepartureInPast);
        if (command.MaxShipments < 1 || command.MaxShipments > ReturnRoute.DefaultMaxShipments)
            return Result<ReturnRoute>.Failure(MatchmakingErrors.InvalidMaxShipments);

        var carrierProfileId = await profilesService.FetchCarrierProfileIdByUserId(command.UserId, cancellationToken);
        if (carrierProfileId is null)
            return Result<ReturnRoute>.Failure(MatchmakingErrors.CarrierProfileNotFound);

        var vehicleMaxLoadKg =
            await profilesService.FetchVehicleMaxLoadKg(carrierProfileId.Value, command.VehicleId, cancellationToken);
        if (vehicleMaxLoadKg is null)
            return Result<ReturnRoute>.Failure(MatchmakingErrors.VehicleNotOwned);

        if (command.DriverId is { } driverId &&
            !await profilesService.OwnsDriver(carrierProfileId.Value, driverId, cancellationToken))
            return Result<ReturnRoute>.Failure(MatchmakingErrors.DriverNotOwned);

        var route = new ReturnRoute(carrierProfileId.Value, command.VehicleId, command.DriverId, command.Origin,
            command.Destination, command.DepartureAt, command.MaxShipments);

        await returnRouteRepository.AddAsync(route, cancellationToken);
        await unitOfWork.CompleteAsync(cancellationToken);

        // The id is generated by the database, so the event is raised once the route is saved.
        route.RaisePublished();
        await unitOfWork.CompleteAsync(cancellationToken);
        return Result<ReturnRoute>.Success(route);
    }

    public async Task<Result<ReturnRoute>> Handle(CancelReturnRouteCommand command,
        CancellationToken cancellationToken)
    {
        var carrierProfileId = await profilesService.FetchCarrierProfileIdByUserId(command.UserId, cancellationToken);
        if (carrierProfileId is null)
            return Result<ReturnRoute>.Failure(MatchmakingErrors.CarrierProfileNotFound);

        var route = await returnRouteRepository.FindByIdAsync(command.ReturnRouteId, cancellationToken);
        if (route is null)
            return Result<ReturnRoute>.Failure(MatchmakingErrors.ReturnRouteNotFound);
        if (route.CarrierProfileId != carrierProfileId.Value)
            return Result<ReturnRoute>.Failure(MatchmakingErrors.NotRouteOwner);

        var error = route.Cancel();
        if (!error.IsNone)
            return Result<ReturnRoute>.Failure(error);

        returnRouteRepository.Update(route);
        await unitOfWork.CompleteAsync(cancellationToken);
        return Result<ReturnRoute>.Success(route);
    }
}
